create table public.song_revisions (
  id bigint generated by default as identity primary key,
  song_id bigint not null references public.songs (id) on delete cascade,
  title text not null,
  strophes jsonb[],
  language text not null,
  source text,
  created_at timestamptz not null default now()
);

create index song_revisions_song_id_created_at_idx
  on public.song_revisions (song_id, created_at desc);

-- No policies: only the service role reads or writes revisions. The trigger
-- below inserts as its owner, so edits made with the anon key are kept too.
alter table public.song_revisions enable row level security;
revoke all on public.song_revisions from anon, authenticated;

-- `source` comes from an `x-edit-source` request header, which PostgREST
-- exposes as the `request.headers` setting. The app doesn't send it, so its
-- edits are stored with a null source.
create function public.keep_song_revision()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.title is distinct from new.title
    or old.strophes is distinct from new.strophes
    or old.language is distinct from new.language then
    insert into public.song_revisions (song_id, title, strophes, language, source)
    values (
      old.id,
      old.title,
      old.strophes,
      old.language,
      nullif(current_setting('request.headers', true), '')::json ->> 'x-edit-source'
    );
  end if;
  return new;
end;
$$;

revoke execute on function public.keep_song_revision() from public, anon, authenticated;

create trigger songs_keep_revision
  before update on public.songs
  for each row execute function public.keep_song_revision();
